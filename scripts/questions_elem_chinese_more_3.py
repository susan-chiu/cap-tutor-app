def Q(unit, concept, difficulty, stem, options, answer, explanation, hints, wrong, check=None):
    # 原稿把正解寫在第一個；這裡依題號輪替正解位置（同步調整 answer 與 wrong 的字母），
    # 讓正解平均分布在 A～D。解析、提示、錯誤原因都不提到選項字母，所以不受影響。
    shift = (len(QUESTIONS) * 3 + 2) % 4
    n = len(options)
    order = [(i - shift) % n for i in range(n)]
    new_pos = {_KEYS[order[i]]: _KEYS[i] for i in range(n)}
    options = [options[j] for j in order]
    answer = new_pos[answer]
    wrong = {new_pos[k]: v for k, v in wrong.items()}
    QUESTIONS.append(dict(unit=unit, concept=concept, difficulty=difficulty, stem=stem,
                          options=options, answer=answer, explanation=explanation,
                          hints=hints, wrong=wrong, check=check))


